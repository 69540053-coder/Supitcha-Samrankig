# ฟังก์ชันแสดงส่วนต้อนรับ
def show_welcome():
    print("==========================================")
    print("   ยินดีต้อนรับสู่เกมทายคำศัพท์ภาษาอังกฤษ  ")
    print("==========================================")
    print("กติกา: พิมพ์คำศัพท์ภาษาอังกฤษที่ตรงกับคำใบ้\n")

# ฟังก์ชันหลักของเกม
def play_vocabulary_game():
    # เก็บข้อมูลคำศัพท์ในรูปแบบ Dictionary (คำศัพท์ : คำใบ้/ความหมาย)
    vocab_dict = {
        "apple": "ผลไม้สีแดงหรือเขียว มีรสชาติหวานกรอบ",
        "computer": "อุปกรณ์อิเล็กทรอนิกส์ที่ใช้ประมวลผลข้อมูล",
        "elephant": "สัตว์บกเลี้ยงลูกด้วยนมขนาดใหญ่ มีงวงยาว",
        "sun": "ดาวฤกษ์ศูนย์กลางระบบสุริยะ ให้แสงสว่างในตอนกลางวัน",
        "book": "สิ่งที่บรรจุตัวอักษรและเรื่องราว เย็บรวมกันเป็นเล่มสำหรับอ่าน"
    }
    
    score = 0
    total_questions = len(vocab_dict)
    
    # ใช้ Loop (for) เพื่อวนถามคำศัพท์ทีละข้อจาก Dictionary
    for word, hint in vocab_dict.items():
        print(f"\n คำใบ้: {hint}")
        user_answer = input("ตอบ (ภาษาอังกฤษ): ").strip().lower()
        
        # ใช้ Condition (if-else) ตรวจสอบความถูกต้อง
        if user_answer == word:
            print("ถูกต้องครับ! เก่งมาก")
            score += 1
        else:
            print(f"ผิดครับ! คำตอบที่ถูกต้องคือ: '{word}'")
            
    # สรุปผลคะแนนเมื่อจบเกม
    print("\n==========================================")
    print("              สรุปผลคะแนน                 ")
    print(f"คุณตอบถูกทั้งหมด {score} จาก {total_questions} ข้อ")
    
    # เงื่อนไขประเมินระดับคะแนน (Conditions)
    if score == total_questions:
        print("ยอดเยี่ยม! คุณได้คะแนนเต็มระดับเซียนคำศัพท์")
    elif score >= 3:
        print("ทำได้ดีมาก! ผ่านเกณฑ์ความรู้พื้นฐาน")
    else:
        print("พยายามอีกนิดนะ! ลองทบทวนคำศัพท์แล้วเล่นใหม่อีกครั้ง")
    print("==========================================")

# โปรแกรมหลัก
def main():
    show_welcome()
    while True:
        play_vocabulary_game()
        play_again = input("\nต้องการเล่นใหม่อีกครั้งหรือไม่? (y/n): ").strip().lower()
        if play_again != 'y':
            print("\n ขอบคุณที่ร่วมสนุก ลาก่อนครับ!")
            break

# รันโปรแกรม
if __name__ == "__main__":
    main()
